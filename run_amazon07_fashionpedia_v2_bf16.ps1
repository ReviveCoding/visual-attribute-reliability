function Show-FileText {
    param([Parameter(Mandatory = $true)][string]$Path)
    if (Test-Path -LiteralPath $Path) {
        $Text = Get-Content -LiteralPath $Path -Raw
        if (-not [string]::IsNullOrWhiteSpace($Text)) {
            Write-Host $Text
        }
    }
}

function Invoke-MatchedHeadArm {
    param([Parameter(Mandatory = $true)][ValidateSet("frozen_head", "lora")][string]$ArmName)

    $BatchPath = Join-Path $RunRoot "run_$ArmName.cmd"
    $StdoutLog = Join-Path $RunRoot "logs\$ArmName.stdout.log"
    $StderrLog = Join-Path $RunRoot "logs\$ArmName.stderr.log"

    $Batch = @"
@echo off
setlocal DisableDelayedExpansion
cd /d "$RepoRoot"
set PYTHONUTF8=1
set HF_HUB_DISABLE_SYMLINKS_WARNING=1
set HF_HUB_DISABLE_PROGRESS_BARS=1

"$VenvPython" -u "$ArmScript" ^
  --arm "$ArmName" ^
  --train-manifest "$TrainManifest" ^
  --dev-manifest "$DevManifest" ^
  --manifest-summary "$ManifestSummary" ^
  --hog-config "$HogConfigPath" ^
  --lora-audit "$LoraAuditJson" ^
  --bf16-preflight "$BF16PreflightJson" ^
  --config "$ConfigPath" ^
  --model-id "$ModelId" ^
  --cache-dir "$CacheRoot" ^
  --run-dir "$RunRoot" ^
  1>"$StdoutLog" ^
  2>"$StderrLog"

exit /b %ERRORLEVEL%
"@

    [System.IO.File]::WriteAllText($BatchPath, $Batch, [System.Text.UTF8Encoding]::new($false))

    Write-Host ""
    Write-Host "============================================================"
    Write-Host "RUN MATCHED-HEAD BF16 ARM: $ArmName"
    Write-Host "============================================================"

    $PriorErrorActionPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = "Continue"
        & $env:ComSpec /d /c "call `"$BatchPath`""
        $ExitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $PriorErrorActionPreference
    }

    Write-Host ""
    Write-Host "===== $ArmName STDOUT ====="
    Show-FileText -Path $StdoutLog
    Write-Host ""
    Write-Host "===== $ArmName STDERR ====="
    Show-FileText -Path $StderrLog

    if ($ExitCode -ne 0) {
        throw "$ArmName BF16 development arm failed with exit code $ExitCode."
    }

    $ArmSummaryPath = Join-Path $RunRoot "$ArmName\arm_summary.json"
    if (-not (Test-Path -LiteralPath $ArmSummaryPath)) {
        throw "$ArmName completed without arm summary: $ArmSummaryPath"
    }

    $ArmSummary = Get-Content -LiteralPath $ArmSummaryPath -Raw | ConvertFrom-Json
    if ($ArmSummary.status -ne "PASS") {
        throw "$ArmName arm returned non-PASS status: $($ArmSummary.status)"
    }

    return $ArmSummary
}

function MetricValue {
    param(
        [Parameter(Mandatory = $true)][object]$Metrics,
        [Parameter(Mandatory = $true)][string]$Name
    )

    $Property = $Metrics.PSObject.Properties[$Name]
    if ($null -eq $Property) { throw "Missing metric '$Name' in arm summary." }
    return [double]$Property.Value
}

function ComparisonRow {
    param(
        [Parameter(Mandatory = $true)][object]$FrozenMetrics,
        [Parameter(Mandatory = $true)][object]$LoraMetrics,
        [Parameter(Mandatory = $true)][string]$MetricName
    )

    $FrozenValue = MetricValue -Metrics $FrozenMetrics -Name $MetricName
    $LoraValue = MetricValue -Metrics $LoraMetrics -Name $MetricName

    return [ordered]@{
        frozen_head = $FrozenValue
        lora = $LoraValue
        lora_minus_frozen_head = $LoraValue - $FrozenValue
    }
}

